"""Outlines the wordmark "isoloop" from Archivo (weight 820, width 68%) into
wordmark.ts, so the lockups render without the font. A one-off tool, not
part of the build: needs Python with fontTools and brotli. Run:
  python3 wordmark.py path/to/archivo-variable.woff2
"""
import re
import sys
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

font = instancer.instantiateVariableFont(TTFont(sys.argv[1]), {"wght": 820, "wdth": 68})
gs = font.getGlyphSet()
cmap = font.getBestCmap()
upm = font["head"].unitsPerEm
asc = font["hhea"].ascent
x = 0
parts = []
for ch in "isoloop":
    name = cmap[ord(ch)]
    pen = SVGPathPen(gs)
    # Flip y (font units point up) and place on the baseline at y = asc.
    gs[name].draw(TransformPen(pen, (1, 0, 0, -1, x, asc)))
    parts.append(re.sub(r"-?\d+\.\d+", lambda m: f"{float(m.group()):.1f}".rstrip("0").rstrip("."), pen.getCommands()))
    x += gs[name].width
xh = font["OS/2"].sxHeight
desc = -font["hhea"].descent
with open("wordmark.ts", "w") as f:
    f.write("// Generated by wordmark.py from Archivo (OFL) at weight 820, width 68%. Do not edit.\n")
    f.write("export const WORDMARK: { d: string; width: number; upm: number; ascent: number; descent: number; xHeight: number } = {\n")
    f.write(f"  d: '{' '.join(parts)}',\n  width: {x},\n  upm: {upm},\n  ascent: {asc},\n  descent: {desc},\n  xHeight: {xh},\n}};\n")
print("width", x, "upm", upm, "asc", asc, "desc", desc, "xh", xh)
